//
// Its only build-time job is collecting `proTab` metadata from page meta
// and emitting `#pro-shell/tabs.mjs` — a `featureId → ProSiteFeatureTab[]`
// map. Everything else (feature definitions, state resolvers, chrome
// components) is registered at runtime via the `pro:feature` hook from
// each layer's `app/plugins/pro-feature.ts`. See ADR-0015 (modernized).
//
// Each pro-* layer plugin looks like:
//
//   import { useGscFeatureDataState } from '../composables/...'
//   import ProGscFeatureChrome from '../internal/components/...'
